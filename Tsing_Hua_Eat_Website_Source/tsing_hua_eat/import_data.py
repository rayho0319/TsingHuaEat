def import_restaurants():
    db_path = os.path.join(os.path.dirname(__file__), 'the.db')
    
    # 依照「在地圖中查看」與「校園地圖尚未涵蓋此地點」來切割每一筆餐廳
    blocks = raw_text.replace('校園地圖尚未涵蓋此地點', '在地圖中查看').split('在地圖中查看')
    
    insert_data = []
    for block in blocks:
        lines = [line.strip() for line in block.strip().split('\n') if line.strip()]
        if not lines:
            continue
            
        name = lines[0]       # 餐廳名稱
        area = lines[1]       # 區域 (小吃部、風雲等)
        category = '校內餐廳' # 預設分類
        price = 0             # 價格先填 0
        
        # 過濾掉無意義的營業狀態文字，將剩下的電話、營業時間、備註用直線串起來當作「簡介」
        desc_lines = [l for l in lines[2:] if l not in ('營業中', '休息中', '即將開始')]
        description = ' | '.join(desc_lines)
        
        insert_data.append((name, category, price, area, description, 0))

    conn = sqlite3.connect(db_path)
    c = conn.cursor()
    c.executemany('''
        INSERT INTO restaurants(name, category, price, area, description, demo)
        VALUES(?,?,?,?,?,?)
    ''', insert_data)
    conn.commit()
    conn.close()
    
    print(f"🎉 恭喜！成功匯入 {len(insert_data)} 家餐廳到資料庫中！")

if __name__ == '__main__':
    import_restaurants()